        story.append(Spacer(1, 10))

        # 5. Top Communicating Hosts & Targeted Ports
        story.append(Paragraph("4. Top Communicating Hosts & Targeted Services", self.styles["SectionHeader"]))
        top_hosts = self.telemetry.get("top_source_ips", [])[:5]
